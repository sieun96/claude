def attach_terms(lessons):
    """각 레슨 본문에 나오는 용어의 인덱스 목록을 붙인다."""
    for l in lessons:
        text = " ".join(str(l.get(k) or "") for k in
                        ("title", "goal", "concepts", "practice", "q", "a", "readout", "use"))
        l["terms"] = [i for i, t in enumerate(TERMS) if any(a in text for a in t[1])]
    return [dict(t=t[0], cat=t[2], d=t[3], ex=t[4]) for t in TERMS]
